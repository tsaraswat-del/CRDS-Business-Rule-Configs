// Tenor convention validation and utility functions:
// Strictly restricts unit to D, W, M, Y (case-insensitive) preceded by any positive number.
export const TENOR_CONVENTION_REGEX = /^[1-9]\d*[DWMYdwmy]$/;

export const isValidTenor = (val: string): boolean => {
  if (!val) return false;
  return TENOR_CONVENTION_REGEX.test(val.trim());
};

export const normalizeTenor = (val: string): string => {
  return val.trim().toUpperCase();
};

export const describeTenor = (val: string): string | null => {
  const trimmed = val.trim();
  if (!isValidTenor(trimmed)) return null;
  const match = trimmed.match(/^(\d+)([DWMYdwmy])$/);
  if (!match) return null;
  const count = parseInt(match[1], 10);
  const unit = match[2].toUpperCase();
  switch (unit) {
    case 'D': return `${count} Day${count === 1 ? '' : 's'}`;
    case 'W': return `${count} Week${count === 1 ? '' : 's'}`;
    case 'M': return `${count} Month${count === 1 ? '' : 's'}`;
    case 'Y': return `${count} Year${count === 1 ? '' : 's'}`;
    default: return null;
  }
};

export const tenorToDays = (val: string): number => {
  const trimmed = val.trim();
  const match = trimmed.match(/^(\d+)([DWMYdwmy])$/);
  if (!match) return 0;
  const count = parseInt(match[1], 10);
  const unit = match[2].toUpperCase();
  switch (unit) {
    case 'D': return count;
    case 'W': return count * 7;
    case 'M': return count * 30;
    case 'Y': return count * 365;
    default: return 0;
  }
};

